"""Embedded deployment: export the learned policy to dependency-free C (float32 and int8 weights),
check bit-level agreement with NumPy, measure host latency/size, and re-run closed loop with int8 weights."""
import json, os, re, subprocess, ctypes, time
import numpy as np
from nn import MLP
from driving import OBS_DIM, evaluate, ACT_SCALE
from run_experiments import test_sets

from paths import RES, BUILD as _B
OUT, BUILD = str(RES), str(_B)


def arr(name, a, ctype="float"):
    return f"static const {ctype} {name}[{a.size}] = {{" + ",".join(f"{v:.9g}" if ctype == "float" else str(int(v)) for v in a.ravel()) + "};\n"


def gen_c(net, int8):
    src = "/* auto-generated by embedded.py */\n#include <stdint.h>\n#include <stddef.h>\n"
    sizes, scales = net.sizes, []
    for i, (W, b) in enumerate(zip(net.W, net.b)):
        if int8:
            s = float(np.abs(W).max() / 127.0); scales.append(s)
            src += arr(f"W{i}", np.round(W / s), "int8_t")
        else:
            scales.append(1.0); src += arr(f"W{i}", W)
        src += arr(f"B{i}", b)
    src += f"#define N0 {sizes[0]}\n#define N1 {sizes[1]}\n#define N2 {sizes[2]}\n#define N3 {sizes[3]}\n"
    src += "static void dense(const float*x,int n,int m,const %s*W,const float*b,float s,float*y,int relu){\n" % ("int8_t" if int8 else "float")
    src += "  for(int j=0;j<m;j++){float a=0.f;for(int i=0;i<n;i++)a+=x[i]*(float)W[i*m+j];a=a*s+b[j];y[j]=(relu&&a<0.f)?0.f:a;}}\n"
    src += "float policy(const float*x){float h1[N1],h2[N2],o[N3];\n"
    src += f"  dense(x,N0,N1,W0,B0,{scales[0]:.9e}f,h1,1);dense(h1,N1,N2,W1,B1,{scales[1]:.9e}f,h2,1);dense(h2,N2,N3,W2,B2,{scales[2]:.9e}f,o,0);\n"
    src += f"  float a=o[0]*{ACT_SCALE}f;return a<-8.f?-8.f:(a>3.f?3.f:a);}}\n"
    src += "#ifdef BENCH\n#include <stdio.h>\n#include <time.h>\nint main(void){float x[N0];for(int i=0;i<N0;i++)x[i]=0.01f*i;volatile float sink=0;\n"
    src += "  struct timespec t0,t1;clock_gettime(CLOCK_MONOTONIC,&t0);for(int k=0;k<200000;k++){x[0]=(float)(k&15)*0.01f;sink+=policy(x);}\n"
    src += "  clock_gettime(CLOCK_MONOTONIC,&t1);printf(\"%.1f\\n\",((t1.tv_sec-t0.tv_sec)*1e9+(t1.tv_nsec-t0.tv_nsec))/200000.0);return 0;}\n#endif\n"
    return src


def numpy_int8(net):
    q = MLP(net.sizes, np.random.default_rng(0)); q.b = [b.copy() for b in net.b]
    q.W = [np.round(W / (np.abs(W).max() / 127.0)) * (np.abs(W).max() / 127.0) for W in net.W]
    return q


if __name__ == "__main__":
    net = MLP([OBS_DIM, 64, 64, 1], np.random.default_rng(0), out_scale=0.1); net.load(f"{OUT}/policy_A_seed0.npz")
    R = dict(params=int(sum(w.size + b.size for w, b in zip(net.W, net.b))), macs=int(sum(w.size for w in net.W)))
    X = np.random.default_rng(0).random((500, OBS_DIM)).astype(np.float32)
    ref = {"float32": np.clip(net.forward(X)[:, 0] * ACT_SCALE, -8, 3), "int8": np.clip(numpy_int8(net).forward(X)[:, 0] * ACT_SCALE, -8, 3)}
    for tag, i8 in (("float32", False), ("int8", True)):
        c = f"{BUILD}/policy_{tag}.c"; open(c, "w").write(gen_c(net, i8))
        for opt in ("-O2", "-Os"):
            exe = f"{BUILD}/bench_{tag}{opt}"
            subprocess.run(["gcc", opt, "-DBENCH", c, "-o", exe], check=True)
            ns = float(subprocess.run([exe], capture_output=True, text=True, check=True).stdout)
            subprocess.run(["gcc", opt, "-c", c, "-o", f"{exe}.o"], check=True)
            sz = subprocess.run(["size", f"{exe}.o"], capture_output=True, text=True).stdout.split("\n")[1].split()
            R[f"{tag}{opt}"] = dict(ns_per_inference=ns, text_bytes=int(sz[0]), data_bytes=int(sz[1]))
        subprocess.run(["gcc", "-O2", "-shared", "-fPIC", c, "-o", f"{BUILD}/lib_{tag}.so"], check=True)
        lib = ctypes.CDLL(f"{BUILD}/lib_{tag}.so"); lib.policy.restype = ctypes.c_float
        lib.policy.argtypes = [ctypes.POINTER(ctypes.c_float)]
        out = np.array([lib.policy(x.ctypes.data_as(ctypes.POINTER(ctypes.c_float))) for x in X])
        R[f"{tag}_max_abs_err_vs_numpy"] = float(np.abs(out - ref[tag]).max())
    Tn, Th, _ = test_sets(); q = numpy_int8(net)
    for nm, m in (("float32", net), ("int8", q)):
        R[f"closed_loop_{nm}"] = {k: float(evaluate(P, m, seed=1)["collided"].mean()) for k, P in (("normal", Tn), ("hazard", Th))}
    R["int8_vs_float_mean_abs_action_diff"] = float(np.abs(ref["int8"] - ref["float32"]).mean())
    json.dump(R, open(f"{OUT}/embedded.json", "w"), indent=1); print(json.dumps(R, indent=1))
